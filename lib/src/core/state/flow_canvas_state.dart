import 'package:lattice/src/core/enums/enums.dart';
import 'package:lattice/src/features/connections/domain/connection_state.dart';
import 'package:lattice/src/features/connections/domain/models/connection.dart';
import 'package:lattice/src/features/edges/domain/edge_state.dart';
import 'package:lattice/src/features/edges/domain/model/edge.dart';
import 'package:lattice/src/features/handles/domain/handle_state.dart';
import 'package:lattice/src/features/nodes/domain/models/node.dart';
import 'package:lattice/src/features/nodes/domain/models/node_state.dart';
import 'package:lattice/src/features/viewport/domain/viewport.dart';
import 'package:flutter/painting.dart';
import 'package:freezed_annotation/freezed_annotation.dart';
import 'package:lattice/src/core/utils/json_converters.dart';
part 'flow_canvas_state.freezed.dart';

@freezed
abstract class FlowCanvasState with _$FlowCanvasState {
  const FlowCanvasState._();

  const factory FlowCanvasState({
    // Core graph data
    @Default({}) @NodeMapConverter() Map<String, FlowNode> nodes,
    @Default({}) Map<String, FlowEdge> edges,

    // Runtime node/edge/handle states
    @Default({})
    @JsonKey(includeFromJson: false, includeToJson: false)
    Map<String, NodeRuntimeState> nodeStates,
    @Default({})
    @JsonKey(includeFromJson: false, includeToJson: false)
    Map<String, EdgeRuntimeState> edgeStates,
    @Default({})
    @JsonKey(includeFromJson: false, includeToJson: false)
    Map<String, HandleRuntimeState> handleStates,

    // Selection and z-ordering
    @Default({}) Set<String> selectedNodes,
    @Default({}) Set<String> selectedEdges,
    @Default(0) int minZIndex,
    @Default(0) int maxZIndex,

    // Viewport
    @Default(FlowViewport()) FlowViewport viewport,
    @SizeConverter() Size? viewportSize,
    @Default(false) bool isPanZoomLocked, // full canvas freeze (not React Flow interactive-only)

    /// Master element-interaction switch (React Flow `setInteractive` /
    /// Controls `showInteractive`): node drag/select, edge select,
    /// connection starts, and marquee selection. Viewport pan/zoom,
    /// pointer observations, and programmatic APIs are unaffected.
    @Default(true)
    @JsonKey(includeFromJson: false, includeToJson: false)
    bool interactive,

    // Interaction state
    @Default(DragMode.none)
    @JsonKey(includeFromJson: false, includeToJson: false)
    DragMode dragMode,
    @JsonKey(includeFromJson: false, includeToJson: false)
    FlowConnection? activeConnection,
    @Default(FlowConnectionRuntimeState.idle())
    @JsonKey(includeFromJson: false, includeToJson: false)
    FlowConnectionRuntimeState connectionState,
    @Default(Rect.zero)
    @RectConverter()
    @JsonKey(includeFromJson: false, includeToJson: false)
    Rect selectionRect,
    @Default('')
    @JsonKey(includeFromJson: false, includeToJson: false)
    String hoveredEdgeId,
    @Default('')
    @JsonKey(includeFromJson: false, includeToJson: false)
    String lastClickedEdgeId,

    /// Bumps when edge paths / geometry cache changes (not on viewport pan).
    @Default(0)
    @JsonKey(includeFromJson: false, includeToJson: false)
    int geometryRevision,

    /// Incremented during node drag so edge [CustomPaint] repaints without hashing all positions.
    @Default(0)
    @JsonKey(includeFromJson: false, includeToJson: false)
    int edgeLiveStamp,
  }) = _FlowCanvasState;

  // toJson is generated by Freezed via _$FlowCanvasStateMixin only if .g.dart exists.
  // Since we use manual serialization, we implement it here:
  //
  // [encodeData] (from the node registry) serializes non-primitive
  // [FlowNode.data] per node `type`; when null, `data` passes through
  // unchanged (primitive/Map data still round-trips).
  Map<String, dynamic> toJson([NodeDataToJson? encodeData]) {
    return {
      'nodes': const NodeMapConverter().toJson(nodes, encodeData),
      'edges': edges.map((k, v) => MapEntry(k, v.toJson())),
      'viewport': viewport.toJson(),
      'isPanZoomLocked': isPanZoomLocked,
      'selectedNodes': selectedNodes.toList(),
      'selectedEdges': selectedEdges.toList(),
      'minZIndex': minZIndex,
      'maxZIndex': maxZIndex,
    };
  }

  /// Decodes a state from JSON. [decodeData] (from the node registry)
  /// rehydrates non-primitive [FlowNode.data] per node `type`; when null,
  /// `data` passes through unchanged.
  factory FlowCanvasState.fromJson(
    Map<String, dynamic> json, [
    NodeDataFromJson? decodeData,
  ]) {
    // Parse core graph data manually from JSON
    final nodesJson = json['nodes'] as Map<String, dynamic>? ?? {};
    final edgesJson = json['edges'] as Map<String, dynamic>? ?? {};

    // NodeMapConverter converts the WHOLE map at once
    final nodes = const NodeMapConverter().fromJson(nodesJson, decodeData);
    final edges = edgesJson.map(
      (k, v) => MapEntry(
        k,
        FlowEdge.fromJson(v as Map<String, dynamic>),
      ),
    );

    // Parse viewport if present
    final viewportJson = json['viewport'] as Map<String, dynamic>?;
    final viewport = viewportJson != null
        ? FlowViewport.fromJson(viewportJson)
        : const FlowViewport();

    return FlowCanvasState(
      nodes: nodes,
      edges: edges,
      viewport: viewport,
      isPanZoomLocked: json['isPanZoomLocked'] as bool? ?? false,
      selectedNodes: ((json['selectedNodes'] as List<dynamic>?) ?? [])
          .map((e) => e as String)
          .toSet(),
      selectedEdges: ((json['selectedEdges'] as List<dynamic>?) ?? [])
          .map((e) => e as String)
          .toSet(),
      minZIndex: json['minZIndex'] as int? ?? 0,
      maxZIndex: json['maxZIndex'] as int? ?? 0,
      // Re-derive runtime state from the parsed graph
      nodeStates: {
        for (final n in nodes.values) n.id: const NodeRuntimeState()
      },
      edgeStates: {
        for (final e in edges.values) e.id: const EdgeRuntimeState()
      },
    );
  }

  factory FlowCanvasState.initial() => const FlowCanvasState(
        nodeStates: {},
        edgeStates: {},
      );

  /// JSON for multiplayer sync: like [toJson] but strips per-client UI state.
  ///
  /// Selection (`selectedNodes`/`selectedEdges`) must never be shared —
  /// every collaborator owns their own — so sync payloads exclude it.
  /// Transient interaction state (drag mode, hover, …) is already excluded
  /// from [toJson]. Pair with `applyRemote`: decode with [fromJson] (missing
  /// selection defaults to empty) and apply — local selection is preserved.
  Map<String, dynamic> toSyncJson([NodeDataToJson? encodeData]) {
    final json = toJson(encodeData);
    json['selectedNodes'] = const <String>[];
    json['selectedEdges'] = const <String>[];
    return json;
  }
}
